// separator 是拼名字时夹在中间那个字，同时也是 Valid() 的切分点。
const separator = "的"

// Words 是词库的对外快照。字段名**就是前端 NICK_WORDS 的键名**，
// 所以 JSON 标签不能改 —— 前端是拿它当对象字面量直接用的。
type Words struct {
	Mood []string `json:"mood"`
	Deed []string `json:"deed"`
	Role []string `json:"role"`
	Name []string `json:"name"`
}

// WordsJSON 返回词库的 JSON —— cmd/gui 把它注入进页面，前端拿它摇名字。
func WordsJSON() string {
	b, err := json.Marshal(Words{Mood: mood, Deed: deed, Role: role, Name: name})
	if err != nil {
		// 全是字面量，编不出错。真出错了给个 null，前端会退回兜底名，
		// 总好过塞半截 JSON 进去把整页脚本搞崩。
		return "null"
	}
	return string(b)
}

// Sample 返回一个合法的样例名字（四张表各取第一个词拼起来）。
//
// 📌 给测试和线上探针用：它们要的是"一个词库里一定存在的名字"。
// 硬编码一个（比如「喜欢捣蛋的雇员沐恩」）的话，改词库时那些地方会莫名其妙地红 ✓
func Sample() string {
	return mood[0] + deed[0] + separator + role[0] + name[0]
}

// 拼名字的两半，各预建一张表用于 O(1) 查。
//
// 📌 为什么拆两半而不是穷举全部名字：全组合是 50^4 = 625 万条，存不下；
// 拆一半就只剩 50×50 = 2500 条，两张表加起来约 5000 条短字符串 ✓
// 内存几百 KB、建表一次（sync.Once）、查一次几纳秒 —— 服务器那边每次注册只查一遍。
var (
	setsOnce sync.Once
	prefixes map[string]bool // 态度 + 做什么
	suffixes map[string]bool // 身份 + 名字
)

func buildSets() {
	prefixes = make(map[string]bool, len(mood)*len(deed))
	for _, m := range mood {
		for _, d := range deed {
			prefixes[m+d] = true
		}
	}
	suffixes = make(map[string]bool, len(role)*len(name))
	for _, r := range role {
		for _, n := range name {
			suffixes[r+n] = true
		}
	}
}

// Valid 判断 label 是不是"词库能拼出来的名字"。
//
// 服务端拿它挡自由字符串：昵称是**客户端生成**的，服务器会把它存进房间、
// 广播给房里所有人、还写进自己的日志 —— 放开就等于把服务器主人的名字挂了上去。
//
// 空串返回 false —— 它在系统里的意思是"没起名"（界面显示「玩家 N」），
// 不是一个"拼出来的名字"。调用方（cmd/signal 的 sanitizeLabel）会先判空再问这里。
func Valid(label string) bool {
	if label == "" {
		return false
	}
	setsOnce.Do(buildSets)
	// 按「的」切 —— 词里没有「的」，所以正常名字只切得出两段。
	// 切出别的段数（没有 / 多个 / 有一头是空）一律判非法。
	parts := strings.Split(label, separator)
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
		return false
	}
	return prefixes[parts[0]] && suffixes[parts[1]]
}
