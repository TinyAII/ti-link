// Package netutil —— 端口策略。
//
// 这一份想解决的问题：不限制的话，我们可以帮人把**任意端口**打洞打出去 ——
// 填 80 就是网站、3389 就是远程桌面、3306 就是数据库 ✗
//
// 🩸 **但先把性质说清楚：这是"提高门槛"，不是"防住"** ✓
//
// 真想滥用的人，把服务换个端口照样能跑（RDP 改成 33389 就行）。
// 所以它的作用是**降低危害和吸引力**，不是准入控制 ✓
//
// 📌 **别对外宣称"我们禁止了 XX 端口"** ✗ —— 那是假的 ✓
// 说"我们把常用服务端口挡了一下，省得顺手就被拿来干别的"就行了 ✓
//
// 🔑 它跟"查进程名"那套的**本质区别**（2026-10-15 那位高人指出来的）：
//
//	查进程名：看起来像防护，实际改个文件名就绕过去了 ⇒ **虚假的安全感** ✗
//	禁端口： 一开始就明说"这只是提高门槛" ⇒ **诚实** ✓
//
// 所以前者去掉了，这个留下了 ✓
package netutil

