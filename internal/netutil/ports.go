// minAllowedPort 之下的端口一律不放行。
//
// 为什么：**1–1023 是"知名端口"**，标准服务都排在这儿
// （HTTP 80 / HTTPS 443 / FTP 21 / SMTP 25 …），而且绑定它们
// 通常需要管理员权限 ⇒ 放出去基本只有坏处 ✓
//
// 📌 游戏联机基本都用高端口 —— 我们的那几个全在 1024 以上 ✓
const minAllowedPort = 1024

// CheckPort 判断这个端口能不能给我们用。
// 返回非空 = **拒绝的理由**（直接给用户看）✓
//
// 🩸 说明：这是个"挡一下顺手"的措施，**不是安全边界** ✗
// 详见文件开头那段 ✓
func CheckPort(port int) string {
	if port <= 0 || port > 65535 {
		return "端口得是 1~65535 之间的数字"
	}

	if port < minAllowedPort {
		// 把常见的那几个单独点出来，用户更容易明白为什么不行 ✓
		if name, ok := wellKnownPorts[port]; ok {
			return fmt.Sprintf("端口 %d 是 %s 的默认端口，不能用来联机。\n"+
				"换成 1024 以上的端口试试（游戏本身的端口是多少就填多少）。", port, name)
		}
		return fmt.Sprintf("端口 %d 在 1~1023 范围内，这里放的是各种系统服务，不能用来联机。\n"+
			"换成 1024 以上的端口试试（游戏本身的端口是多少就填多少）。", port)
	}

	if what, ok := riskyPorts[port]; ok {
		return fmt.Sprintf("端口 %d 是 %s 常用的端口，不能用来联机。\n"+
			"如果游戏真的用的就是这个端口，那只能换个端口开了。", port, what)
	}

	return ""
}

// PortOf 从 "127.0.0.1:24642" 里取端口号 ✓
//
// 📌 全项目**只有这一个**从地址取端口的地方 ——
// 之前 internal/game 里也写过一份，两边迟早会不一致 ✗
// （跟"数据目录只有一个来源"是一个道理 ✓）
func PortOf(addr string) (int, error) {
	_, p, err := net.SplitHostPort(addr)
	if err != nil {
		return 0, err
	}
	n, err := strconv.Atoi(p)
	if err != nil {
		return 0, err
	}
	if n < 1 || n > 65535 {
		return 0, fmt.Errorf("端口 %d 超出范围", n)
	}
	return n, nil
}

